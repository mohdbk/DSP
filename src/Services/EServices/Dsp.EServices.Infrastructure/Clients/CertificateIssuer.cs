using System.Net;
using System.Net.Http.Headers;
using System.Net.Http.Json;
using System.Text;
using Dsp.EServices.Application;
using Dsp.EServices.Domain.Applications;
using Dsp.EServices.Domain.Catalog;

namespace Dsp.EServices.Infrastructure.Clients;

/// <summary>Renders a simple bilingual certificate and stores it through the Documents service.</summary>
public sealed class CertificateIssuer(HttpClient http, IServiceCatalog catalog) : ICertificateIssuer
{
    public async Task<Guid> IssueAsync(ServiceApplication application, CancellationToken ct)
    {
        var service = await catalog.FindVersionAsync(application.ServiceCode, application.ServiceVersion, ct)
                      ?? await catalog.FindPublishedAsync(application.ServiceCode, ct);
        var html = Render(application, service);
        using var content = new MultipartFormDataContent();
        var file = new ByteArrayContent(Encoding.UTF8.GetBytes(html));
        file.Headers.ContentType = new MediaTypeHeaderValue("text/html");
        content.Add(file, "file", $"certificate-{application.Number}.html");
        content.Add(new StringContent(application.ApplicantId), "ownerId");
        content.Add(new StringContent("Certificate"), "kind");

        var response = await http.PostAsync("/internal/documents", content, ct);
        response.EnsureSuccessStatusCode();
        var created = await response.Content.ReadFromJsonAsync<Created>(ct)
                      ?? throw new InvalidOperationException("Documents returned no body.");
        return created.Id;
    }

    private static string Render(ServiceApplication a, ServiceDefinition? service)
    {
        var data = a.GetData();
        var rows = new StringBuilder();
        if (service is not null)
        {
            foreach (var field in service.AllFields.Where(f => f.Type is not ("checkbox" or "file")))
            {
                if (!data.TryGetValue(field.Key, out var value) || string.IsNullOrWhiteSpace(value)) continue;
                var option = field.Options?.FirstOrDefault(o => o.Value == value);
                var display = option is null ? value : option.LabelAr is null ? option.Label : $"{option.Label} · {option.LabelAr}";
                var label = field.LabelAr is null ? field.Label : $"{field.Label} · {field.LabelAr}";
                rows.Append($"<tr><th>{E(label)}</th><td>{E(display)}</td></tr>");
            }
        }

        return $$"""
            <!doctype html>
            <html lang="en"><head><meta charset="utf-8"><title>Certificate {{E(a.Number)}}</title>
            <style>
              body{font-family:Inter,Roboto,Arial,sans-serif;color:#1a1c20;margin:0;padding:48px;background:#fefcf4}
              .card{max-width:760px;margin:auto;background:#fff;border:2px solid #90702a;border-radius:12px;padding:40px}
              h1{color:#90702a;margin:0 0 4px} .ar{direction:rtl;font-size:20px;color:#7c5a22}
              table{width:100%;border-collapse:collapse;margin-top:24px} th,td{text-align:left;padding:8px;border-bottom:1px solid #dbcca1}
              th{width:40%;color:#4b4f58;font-weight:600} .meta{margin-top:24px;color:#4b4f58;font-size:13px}
            </style></head>
            <body><div class="card">
              <div>Ministry of Economy and Tourism · وزارة الاقتصاد والسياحة</div>
              <h1>{{E(a.ServiceName)}}</h1>
              <div class="ar">{{E(service?.NameAr ?? "")}}</div>
              <p>This certifies that the application below was approved.<br><span dir="rtl">نشهد بأنه تمت الموافقة على الطلب الموضح أدناه.</span></p>
              <table>
                <tr><th>Certificate number · رقم الشهادة</th><td>{{E(a.Number)}}</td></tr>
                <tr><th>Holder · صاحب الشهادة</th><td>{{E(a.ApplicantName)}}</td></tr>
                {{rows}}
                <tr><th>Issued · تاريخ الإصدار</th><td>{{DateTimeOffset.UtcNow:dd MMM yyyy}}</td></tr>
              </table>
              <div class="meta">Proof-of-concept certificate generated by the Digital Services Platform. Not a legal document.</div>
            </div></body></html>
            """;
    }

    private static string E(string? value) => WebUtility.HtmlEncode(value ?? "");

    private sealed record Created(Guid Id);
}
